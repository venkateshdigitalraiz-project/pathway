  // Gender options: 'Male', 'Female', 'Others'
  String _selectedGender = 'Male';

  @override
  void initState() {
    super.initState();
    final authState = context.read<AuthBloc>().state;
    final user = authState.user;
    final phone = authState.phoneNumber.isNotEmpty
        ? authState.phoneNumber
        : (user?.phoneNumber ?? '');

    final storage = AuthLocalStorage();
    final savedName = storage.getFullName(phone);
    final savedEmail = storage.getEmail(phone);
    final savedGender = storage.getGender(phone);
    final savedRef = storage.getReference(phone);

    final rawName = (savedName != null && savedName.isNotEmpty)
        ? savedName
        : (user?.fullName.trim() ?? '');

    // Do not pre-fill with auto-generated placeholder names like "User 9999", "User", etc.
    // Leave blank so only the clean hint text ('e.g. Rama Krishna') is displayed.
    final isAutoGeneratedName =
        rawName.isEmpty ||
        rawName.toLowerCase() == 'user' ||
        rawName.toLowerCase().startsWith('user') ||
        RegExp(r'^user[\s_-]*\d*$', caseSensitive: false).hasMatch(rawName);

    if (!isAutoGeneratedName) {
      _fullNameController.text = rawName;
    }

    final rawEmail = (savedEmail != null && savedEmail.isNotEmpty)
        ? savedEmail
        : (user?.email ?? '');
    if (rawEmail.isNotEmpty && !rawEmail.contains('@pathway.com')) {
      _emailController.text = rawEmail;
    }

    final rawGender = (savedGender != null && savedGender.isNotEmpty)
        ? savedGender
        : user?.gender;
    if (rawGender != null && rawGender.isNotEmpty) {
      _selectedGender = rawGender;
    }

    final rawRef = (savedRef != null && savedRef.isNotEmpty)
        ? savedRef
        : user?.reference;
    if (rawRef != null && rawRef.isNotEmpty) {
      _referenceController.text = rawRef;
    }
  }

  @override
  void dispose() {
    _fullNameController.dispose();
    _emailController.dispose();
    _referenceController.dispose();
    _fullNameFocus.dispose();
    _emailFocus.dispose();
    _referenceFocus.dispose();
    super.dispose();
  }

  void _onSubmit() {
    FocusScope.of(context).unfocus();
    if (!(_formKey.currentState?.validate() ?? false)) {
      return;
    }

    final authState = context.read<AuthBloc>().state;
    final phone = authState.phoneNumber.isNotEmpty
        ? authState.phoneNumber
        : (authState.user?.phoneNumber ?? '');

    // Synchronously ensure SharedPreferences has custom details stored
    AuthLocalStorage().saveCustomUserDetails(
      fullName: _fullNameController.text.trim(),
      email: _emailController.text.trim(),
      reference: _referenceController.text.trim().isNotEmpty
          ? _referenceController.text.trim()
          : null,
      gender: _selectedGender,
      phone: phone,
    );
    AuthLocalStorage().setProfileCompleted(true, phone: phone);

    context.read<AuthBloc>().add(
      SaveUserDetailsEvent(
        fullName: _fullNameController.text.trim(),
        email: _emailController.text.trim(),
        reference: _referenceController.text.trim().isNotEmpty
            ? _referenceController.text.trim()
            : null,
        gender: _selectedGender,
      ),
    );
  }

